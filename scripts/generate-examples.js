#!/usr/bin/env node
/* Regenerates every file in examples/ from the inputs in examples/inputs/, using the real engine.
   Fails (exit 1) if any example has lint hits, no blocks, or spintax that does not parse back cleanly.
   Usage: node scripts/generate-examples.js */
const fs = require("fs"), path = require("path");
const S = require("../src/spintax.js");

const ROOT = path.join(__dirname, "..", "examples");
const read = dir => fs.readdirSync(path.join(ROOT, "inputs", dir)).filter(f => f.endsWith(".txt")).sort()
  .map(f => ({ id: f.replace(/\.txt$/, ""), text: fs.readFileSync(path.join(ROOT, "inputs", dir, f), "utf8").trimEnd() }));
const CLEAN = read("clean"), DRAFTS = read("ai-drafts");

const NAME = { bison: "EmailBison", smartlead: "Smartlead", instantly: "Instantly" };
const nativePlatform = t => /\{\{\s*[a-z]+[A-Z]\w*\s*(\|[^}]*)?\}\}|\{\{accountSignature\}\}/.test(t) ? "instantly" : /\{[A-Z_]+\}/.test(t) ? "bison" : "smartlead";
const MODES = { word: "Word-level", sentence: "Sentence-level", mixed: "Mixed" };
const INTS = { 50: 0.5, 80: 0.8, 100: 1 };
const fence = t => "```text\n" + t + "\n```";

const problems = [], all = { generated: "by scripts/generate-examples.js", functions: {} };
const stats = res => { const c = S.check(res, 1000); return { blocks: c.blocks, versions: S.fmtBig(c.combos), lint: c.lint.reduce((a, x) => a + x.count, 0), worstGrade: +c.worst.g.toFixed(1), words: c.words }; };
const verify = (fn, id, res, st) => {
  const out = S.serialize(res), back = S.parse(out, res.platform);
  if (st.lint) problems.push(`${fn}/${id}: ${st.lint} lint hits`);
  if (!st.blocks) problems.push(`${fn}/${id}: no blocks`);
  if (back.errors.length) problems.push(`${fn}/${id}: parse errors ${back.errors.join("; ")}`);
  if (S.serialize(back.res) !== out) problems.push(`${fn}/${id}: parse round-trip differs`);
};

let n = 0;
const files = [];
// 1-9: every mode at every intensity
for (const mode of Object.keys(MODES)) for (const pct of Object.keys(INTS)) {
  const fn = `${mode}-${pct}`, title = `${MODES[mode]} spintax at ${pct}%`;
  const items = CLEAN.map((inp, k) => {
    const platform = nativePlatform(inp.text);
    const res = S.build(inp.text, { platform, mode, intensity: INTS[pct], humanize: false, convert: true, seed: 11 + k });
    const st = stats(res); verify(fn, inp.id, res, st);
    const r = S.rng(5 + k);
    return { id: inp.id, platform, settings: { platform, mode, intensity: INTS[pct], humanize: false }, input: inp.text, output: S.serialize(res), stats: st, renders: [S.render(res, r), S.render(res, r)] };
  });
  all.functions[fn] = { title, items };
  files.push([`${String(++n).padStart(2, "0")}-${fn}.md`, fn, title, items]);
}

// 10: humanize
const hz = DRAFTS.map(inp => { const h = S.humanize(inp.text); return { id: inp.id, input: inp.text, output: h.text, changes: h.changes }; });
hz.forEach(h => { if (/[—–]/.test(h.output)) problems.push(`humanize/${h.id}: dash left`); if (!h.changes.length) problems.push(`humanize/${h.id}: no changes`); });
all.functions.humanize = { title: "Humanize (clean up AI-sounding copy)", items: hz };

// 11: humanize, then spin (the default in the web app)
const hzs = DRAFTS.map((inp, k) => {
  const platform = nativePlatform(inp.text);
  const res = S.build(inp.text, { platform, mode: "word", intensity: 0.8, humanize: true, convert: true, seed: 31 + k });
  const st = stats(res); verify("humanize-then-spin", inp.id, res, st);
  return { id: inp.id, platform, settings: { platform, mode: "word", intensity: 0.8, humanize: true }, input: inp.text, output: S.serialize(res), changes: res.humanized, stats: st, renders: [S.render(res, S.rng(9 + k))] };
});
all.functions["humanize-then-spin"] = { title: "Humanize, then spin (word-level, 80%)", items: hzs };

// 12: platform conversion of existing spintax
const ORDER = ["smartlead", "bison", "instantly"];
const conv = CLEAN.map((inp, k) => {
  const from = nativePlatform(inp.text), to = ORDER[(ORDER.indexOf(from) + 1) % 3];
  const src = S.serialize(S.build(inp.text, { platform: from, mode: "mixed", intensity: 0.8, humanize: false, convert: true, seed: 51 + k }));
  const c = S.convertSyntax(src, to), back = S.parse(c.text, to);
  if (back.errors.length) problems.push(`convert/${inp.id}: ${back.errors.join("; ")}`);
  return { id: inp.id, from, to, input: src, output: c.text, changes: c.log };
});
all.functions.convert = { title: "Convert spintax between platforms", items: conv };

/* ---------- write markdown ---------- */
const head = (title, what) => `# ${title}\n\n${what}\n\nGenerated by \`scripts/generate-examples.js\` from \`examples/inputs/\`. Every example below was checked: 1,000 random renders with 0 grammar-lint hits, and the spintax parses back cleanly for its platform.\n`;
const WHAT = {
  word: "Swaps words and short phrases inside each sentence, like `I {noticed|saw}`. Meaning and length stay the same. Merge tags, the signature, links and numbers are never spun.",
  sentence: "Offers two to four complete versions of whole sentences, like `{Worth a quick chat?|Open to a short call?}`. Sentences that contain a merge tag, link or signature fall back to word swaps so the tag never lands inside a block.",
  mixed: "Word swaps inside the body, plus whole-sentence blocks for the lines everyone writes: the CTA, the opt-out, the follow-up bump and the sign-off.",
};
const INT = { 50: "About half of the phrases the knowledge base knows get a block.", 80: "Most phrases get a block. A good default for lists over 2,000.", 100: "Every phrase the knowledge base knows gets a block, with up to four options each." };
for (const [file, fn, title, items] of files) {
  const [mode, pct] = fn.split("-");
  let md = head(title, `**Mode:** ${WHAT[mode]}\n\n**Intensity:** ${INT[pct]}`);
  items.forEach((it, i) => {
    md += `\n---\n\n## Example ${i + 1}: ${it.id.replace(/^\d+-/, "").replace(/-/g, " ")}\n\n**Platform:** ${NAME[it.platform]} · **Blocks:** ${it.stats.blocks} · **Unique versions:** ${it.stats.versions} · **Worst reading grade:** ${it.stats.worstGrade} · **Lint hits:** ${it.stats.lint}\n\n**Input**\n\n${fence(it.input)}\n\n**Spintax**\n\n${fence(it.output)}\n\n**Two random renders**\n\n${fence(it.renders[0])}\n\n${fence(it.renders[1])}\n`;
  });
  fs.writeFileSync(path.join(ROOT, file), md);
}
let md = head("Humanize: clean up AI-sounding copy", "Rule-based rewrite that removes the patterns that make cold email read as machine-written: stock openers, dashes, filler, inflated vocabulary and pushy sign-offs. Merge tags and the signature are protected. See `skills/cold-email-humanizer/` for the full rule set.");
hz.forEach((h, i) => { md += `\n---\n\n## Example ${i + 1}: ${h.id.replace(/^\d+-/, "").replace(/-/g, " ")}\n\n**Before**\n\n${fence(h.input)}\n\n**After**\n\n${fence(h.output)}\n\n**What changed:** ${h.changes.map(c => `${c.label}${c.count > 1 ? ` (${c.count})` : ""}`).join(" · ")}\n`; });
fs.writeFileSync(path.join(ROOT, `${String(++n).padStart(2, "0")}-humanize.md`), md);
md = head("Humanize, then spin", "The web app's default: clean the copy first, then spin it word by word at 80%.");
hzs.forEach((h, i) => { md += `\n---\n\n## Example ${i + 1}: ${h.id.replace(/^\d+-/, "").replace(/-/g, " ")}\n\n**Platform:** ${NAME[h.platform]} · **Blocks:** ${h.stats.blocks} · **Unique versions:** ${h.stats.versions} · **Lint hits:** ${h.stats.lint}\n\n**Input**\n\n${fence(h.input)}\n\n**Humanized and spun**\n\n${fence(h.output)}\n\n**One render**\n\n${fence(h.renders[0])}\n\n**Humanize changes:** ${h.changes.map(c => c.label).join(" · ")}\n`; });
fs.writeFileSync(path.join(ROOT, `${String(++n).padStart(2, "0")}-humanize-then-spin.md`), md);
md = head("Convert spintax between platforms", "Rewrites existing spin blocks, merge tags and the signature tag into the target platform's syntax without adding or removing any variation. Inline fallbacks such as `{{first_name|there}}` are kept for Instantly and dropped (with a note) for EmailBison and Smartlead, which have no inline fallback.");
conv.forEach((c, i) => { md += `\n---\n\n## Example ${i + 1}: ${NAME[c.from]} to ${NAME[c.to]}\n\n**${NAME[c.from]} spintax**\n\n${fence(c.input)}\n\n**${NAME[c.to]} spintax**\n\n${fence(c.output)}\n\n**What changed:** ${c.changes.join(" · ")}\n`; });
fs.writeFileSync(path.join(ROOT, `${String(++n).padStart(2, "0")}-convert.md`), md);

// browser copy for AI mode's worked examples (input and output only, so the page stays light)
const lite = { functions: Object.fromEntries(Object.entries(all.functions).filter(([k]) => /^(word|sentence|mixed)-/.test(k)).map(([k, f]) => [k, { items: f.items.map(x => ({ platform: x.platform, input: x.input, output: x.output })) }])) };
fs.writeFileSync(path.join(ROOT, "examples.js"), "/* Generated by scripts/generate-examples.js. Used by AI mode in the browser. */\nwindow.SPINTAX_EXAMPLES = " + JSON.stringify(lite) + ";\n");
fs.writeFileSync(path.join(ROOT, "examples.json"), JSON.stringify(all, (k, v) => typeof v === "bigint" ? v.toString() : v, 1));
const total = Object.values(all.functions).reduce((a, f) => a + f.items.length, 0);
console.log(`${Object.keys(all.functions).length} functions, ${total} examples written to examples/`);
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
